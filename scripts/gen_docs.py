"""Generate docs/config.schema.json, docs/configuration.md and docs/tools.md.

The first two come from the config and tool group models, tools.md from the tool list the server
publishes. Run `uv run python scripts/gen_docs.py` after changing a setting or a tool. With
`--check` nothing is written and the exit status is 1 if a file is out of date.

tools.md covers every built-in group, so this needs every extra installed (`uv sync --all-extras`);
without one it exits with status 2 and says so.
"""

from __future__ import annotations

import argparse
import asyncio
import inspect
import json
import logging
import sys
import tempfile
from pathlib import Path
from typing import Any

import mcp.types as types

from dev_link_mcp.app import assemble
from dev_link_mcp.config import Config
from dev_link_mcp.config.loader import SECTIONS
from dev_link_mcp.config.schema import schema
from dev_link_mcp.tools import BUILTINS, install_hint, load_group_class, missing_requirements

DOCS = Path(__file__).resolve().parents[1] / "docs"

INTRO = """\
# Configuration

<!-- Generated by scripts/gen_docs.py from the config and tool group models. Do not edit by hand. -->

dev-link reads its settings from these layers. A later layer overrides an earlier one:

1. Built-in defaults (listed below).
2. The user file `$XDG_CONFIG_HOME/dev-link/config.yaml` (usually `~/.config/dev-link/config.yaml`), if it exists.
3. The file passed with `--config FILE`. It must exist.
4. Environment variables named `DEV_LINK_*`.
5. Command-line flags.

Sections such as `server` merge key by key, so a layer only changes the keys it sets. Any other
value, including a list or the `sandbox.env` mapping, is replaced whole. The repeatable flags
`--enable`, `--disable` and `--allowed-host` are the exception: they add to the list built by the
layers below.

Unknown keys and values of the wrong type stop the server with an error that names the key and
the layer it came from. Editors that support JSON Schema can check a config file against
[config.schema.json](config.schema.json). The tools of each group and their parameters are listed
in [tools.md](tools.md).

## Environment variables

A key in a section is set with `DEV_LINK_<SECTION>__<KEY>` (two underscores), for example
`DEV_LINK_SANDBOX__NETWORK=false` or `DEV_LINK_SERVER__PORT=9000`. The top-level keys are
`DEV_LINK_STATE_DIR` and `DEV_LINK_LOG_LEVEL`. Strings and paths are used as written; other values
are read as YAML, so `false`, `30` and `[http, browser]` work.

A tool group setting is set with `DEV_LINK_GROUPS__<GROUP>__<KEY>`, for example
`DEV_LINK_GROUPS__BROWSER__HEADLESS=false`. These values are always read as YAML, so quote a string
that looks like a number or a boolean.

The workspace cannot be set from the environment. Commands run by the agent see
`DEV_LINK_WORKSPACE`, and dev-link ignores it. Other unknown `DEV_LINK_*` variables are ignored
with a warning.

## Files inside the workspace are never read

The agent can write anywhere in the workspace, so a config file there could turn off the sandbox
for the next start. dev-link never looks for config files in the workspace, and it refuses a
`--config` file or user file whose path is inside it.

## Example

```yaml
server:
  port: 9000
sandbox:
  network: false
  env:
    PORT: "3000"
tools:
  enabled: [docker]
  disabled_tools: [browser_eval]
groups:
  browser:
    headless: false
```
"""

GROUPS_INTRO = """\
## Tool groups

Tools come in groups. Every built-in group is on unless `tools.disabled` lists it, except
`docker`, which also needs `tools.enabled` (or `--enable docker`). `tools.disabled_tools` removes
single tools. An unknown name in `tools.enabled`, `tools.disabled`, `tools.disabled_tools` or
`groups` stops the server, so a typo cannot go unnoticed.

The `browser` and `code` groups need extra packages: install `dev-link-mcp[browser]`,
`dev-link-mcp[code]`, or `dev-link-mcp[all]` for both. Without them the group is reported as not
installed, in the log, on the dashboard and by `workspace_info`, and the server starts without it.

Each group reads its settings from `groups.<name>`, merged key by key like a section. Settings
of a group that is turned off or not installed are not checked.

### Plugins

Other packages can add tool groups; see [extending.md](extending.md). An installed plugin is
loaded only when `tools.enabled` lists its name, so installing a package never adds tools by
itself. Plugins run inside the dev-link server process, outside the sandbox: install only
plugins you trust.
"""


def _type(prop: dict[str, Any]) -> str:
    if "enum" in prop:
        return "one of " + ", ".join(f"`{v}`" for v in prop["enum"])
    if "anyOf" in prop:
        return " or ".join(_type(p) for p in prop["anyOf"])
    kind = prop["type"]
    if kind == "array":
        return f"list of {_type(prop['items'])}s"
    if kind == "object":
        values = prop.get("additionalProperties")
        return f"mapping of string to {_type(values)}" if isinstance(values, dict) else "mapping"
    if kind == "string" and prop.get("format") == "path":
        return "path"
    if "minimum" in prop and "maximum" in prop:
        return f"{kind} ({prop['minimum']} to {prop['maximum']})"
    return kind


def _table(properties: dict[str, Any], prefix: str = "") -> list[str]:
    rows = ["| Key | Type | Default | Description |", "| --- | --- | --- | --- |"]
    for name, prop in properties.items():
        default = f"`{json.dumps(prop['default'])}`" if "default" in prop else "required"
        description = prop["description"].replace("|", "\\|")
        rows.append(f"| `{prefix}{name}` | {_type(prop)} | {default} | {description} |")
    return rows


def markdown(file_schema: dict[str, Any]) -> str:
    """The configuration reference: an intro, then one table per section."""
    top = {k: v for k, v in file_schema["properties"].items() if k not in SECTIONS}
    lines = [INTRO, "## Top-level keys", "", *_table(top)]
    for name, model in SECTIONS.items():
        section = file_schema["$defs"][model.__name__]
        lines += ["", f"## `{name}`", "", file_schema["properties"][name]["description"], ""]
        lines += _table(section["properties"], f"{name}.")
    lines += ["", GROUPS_INTRO.rstrip("\n")]
    for b in BUILTINS:
        cls = load_group_class(b.target)
        notes = [inspect.getdoc(cls) or ""]
        if cls.opt_in:
            notes.append("Opt-in: off unless `tools.enabled` lists it.")
        if b.requires:
            notes.append(f"Needs `dev-link-mcp[{b.name}]`.")
        lines += ["", f"### `groups.{b.name}`", "", " ".join(notes), ""]
        settings = file_schema["$defs"][cls.Settings.__name__]["properties"]
        lines += _table(settings, f"groups.{b.name}.") if settings else ["No settings."]
    return "\n".join(lines) + "\n"


TOOLS_INTRO = """\
# Tools

<!-- Generated by scripts/gen_docs.py from the tool list the server publishes. Do not edit by hand. -->

These are the tools a client sees, grouped by tool group, with every built-in group turned on.
Descriptions and parameters are exactly what the server publishes.

Turn a group off with `tools.disabled` (or `--disable GROUP`), turn on an opt-in group with
`tools.enabled` (or `--enable GROUP`), and remove single tools with `tools.disabled_tools`; see
[configuration.md](configuration.md#tool-groups). `dev-link tools` lists the tools a given
configuration publishes.
"""

_BOUNDS = (
    ("minimum", ">= {}"),
    ("exclusiveMinimum", "> {}"),
    ("maximum", "<= {}"),
    ("exclusiveMaximum", "< {}"),
    ("minItems", "{} or more items"),
    ("maxItems", "up to {} items"),
    ("minLength", "{} or more characters"),
    ("maxLength", "up to {} characters"),
)


async def published_tools() -> tuple[dict[str, list[str]], dict[str, types.Tool]]:
    """Group name -> its tool names, and tool name -> the tool as `list_tools()` publishes it.

    Every built-in group is on, opt-in ones included. The server is assembled in a throwaway
    workspace and state dir with the sandbox off, so the result does not depend on bwrap, Chromium
    or docker, and no tool runs.
    """
    opt_in = [b.name for b in BUILTINS if load_group_class(b.target).opt_in]
    # The `none` sandbox backend warns that commands run unconfined; nothing runs here.
    logger = logging.getLogger("dev_link_mcp")
    level = logger.level
    logger.setLevel(logging.ERROR)
    try:
        with tempfile.TemporaryDirectory(prefix="dev-link-gen-docs-") as scratch:
            workspace = Path(scratch) / "ws"
            workspace.mkdir()
            config = Config(
                workspace=workspace,
                state_dir=Path(scratch) / "state",
                sandbox={"backend": "none"},
                tools={"enabled": opt_in},
            ).finalize()
            mcp, rt, toolset = await assemble(config)
            try:
                tools = {tool.name: tool for tool in await mcp.list_tools()}
            finally:
                await toolset.shutdown()
                await rt.processes.shutdown()
                rt.audit.close()
    finally:
        logger.setLevel(level)
    return toolset.tools, tools


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _param_type(prop: dict[str, Any]) -> str:
    if "$ref" in prop:
        return f"`{prop['$ref'].rsplit('/', 1)[-1]}`"
    if "enum" in prop:
        return "one of " + ", ".join(f"`{v}`" for v in prop["enum"])
    if "anyOf" in prop:
        return " or ".join(_param_type(p) for p in prop["anyOf"])
    kind = prop.get("type")
    if kind is None:
        return "any"
    if kind == "array":
        kind = f"list of {_param_type(prop['items'])}" if prop.get("items") else "list"
    elif kind == "object":
        values = prop.get("additionalProperties")
        kind = f"mapping of string to {_param_type(values)}" if isinstance(values, dict) else "object"
    bounds = [text.format(prop[key]) for key, text in _BOUNDS if key in prop]
    return f"{kind} ({', '.join(bounds)})" if bounds else kind


def _param_table(object_schema: dict[str, Any]) -> list[str]:
    required = set(object_schema.get("required", []))
    rows = ["| Parameter | Type | Required | Default | Description |", "| --- | --- | --- | --- | --- |"]
    for name, prop in object_schema.get("properties", {}).items():
        default = f"`{_cell(json.dumps(prop['default']))}`" if "default" in prop else "-"
        needed = "yes" if name in required else "no"
        description = _cell(prop.get("description", ""))
        rows.append(f"| `{name}` | {_cell(_param_type(prop))} | {needed} | {default} | {description} |")
    return rows


def _tool_section(tool: types.Tool) -> list[str]:
    lines = [f"### `{tool.name}`", "", (tool.description or "").strip(), ""]
    input_schema = tool.input_schema
    if input_schema.get("properties"):
        lines += _param_table(input_schema)
    else:
        lines.append("No parameters.")
    for name, definition in input_schema.get("$defs", {}).items():
        lines += ["", f"`{name}` fields:", "", *_param_table(definition)]
    if tool.output_schema is not None:
        lines += ["", "Returns structured output (`structuredContent`) as well as text."]
    else:
        lines += ["", "Returns text only."]
    return lines


def tools_markdown(groups: dict[str, list[str]], tools: dict[str, types.Tool]) -> str:
    """The tool reference: an intro and a summary table, then each group's tools in BUILTINS order."""
    summary = ["| Group | On by default | Needs extra | Tools |", "| --- | --- | --- | --- |"]
    sections: list[str] = []
    for b in BUILTINS:
        cls = load_group_class(b.target)
        names = groups[b.name]
        extra = f"`{b.name}`" if b.requires else "-"
        summary.append(f"| [`{b.name}`](#{b.name}) | {'no' if cls.opt_in else 'yes'} | {extra} | {len(names)} |")
        notes = [inspect.getdoc(cls) or ""]
        notes.append("Opt-in: off unless `tools.enabled` lists it." if cls.opt_in else "On by default.")
        if b.requires:
            notes.append(f"Needs the `{b.name}` extra: `{install_hint(b)}`.")
        sections += ["", f"## {b.name}", "", " ".join(notes)]
        for name in names:
            sections += ["", *_tool_section(tools[name])]
    total = sum(len(names) for names in groups.values())
    lines = [TOOLS_INTRO, f"{total} tools in {len(groups)} groups.", "", *summary, *sections]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if a generated file is out of date")
    args = parser.parse_args()
    missing = [b.name for b in BUILTINS if missing_requirements(b)]
    if missing:
        print(
            f"docs/tools.md lists every tool group and needs every extra; not installed: {', '.join(missing)}."
            " Run: uv sync --all-extras",
            file=sys.stderr,
        )
        return 2
    file_schema = schema()
    groups, tools = asyncio.run(published_tools())
    outputs = {
        DOCS / "config.schema.json": json.dumps(file_schema, indent=2) + "\n",
        DOCS / "configuration.md": markdown(file_schema),
        DOCS / "tools.md": tools_markdown(groups, tools),
    }
    stale = [path for path, text in outputs.items() if not path.is_file() or path.read_text() != text]
    if args.check:
        for path in stale:
            print(f"{path} is out of date; run: uv run python scripts/gen_docs.py", file=sys.stderr)
        return 1 if stale else 0
    DOCS.mkdir(exist_ok=True)
    for path in stale:
        path.write_text(outputs[path])
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
